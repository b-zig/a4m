"""`a4m build`: OEF for Archi + Markdown/Mermaid docs for GitHub and VS Code."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .adr import adrs_affecting
from .export_c4 import render_c4
from .export_mermaid import render_archimate
from .export_oef import export_oef
from .model import Model, View
from .paths import workspace_root
from .rules import Rules, load_rules
from .state import LEGEND, at_state, has_changes
from .views import view_members, view_relationships

MARKER = "<!-- generated by a4m build; edit models/, not this file -->"


@dataclass
class BuildResult:
    oef: Path
    docs: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def render_view(model: Model, view: View, rules: Rules | None = None, state: str | None = None) -> str:
    """Mermaid for a view in its own state (default "change"), or in `state` (change/baseline/target)."""
    rules = rules or load_rules()
    state = state or view.state
    shown = at_state(model, state)
    styled = state == "change"
    return render_c4(shown, view, rules, styled) if view.is_c4 else render_archimate(shown, view, rules, styled)


def view_has_changes(model: Model, view: View, rules: Rules) -> bool:
    members = view_members(model, view, rules)
    return has_changes(model, members, view_relationships(model, members))


def build(model: Model, root: Path | None = None, rules: Rules | None = None) -> BuildResult:
    rules = rules or load_rules()
    root = root or workspace_root()
    oef_path = root / "build" / f"{model.sa}.oef.xml"
    oef_path.parent.mkdir(parents=True, exist_ok=True)
    oef_path.write_text(export_oef(model, rules), encoding="utf-8")

    docs_dir = root / "docs" / model.sa
    docs_dir.mkdir(parents=True, exist_ok=True)
    result = BuildResult(oef_path)
    written: set[Path] = set()

    def write(name: str, text: str) -> None:
        path = docs_dir / name
        path.write_text(f"{MARKER}\n{text}", encoding="utf-8")
        written.add(path)
        result.docs.append(path)

    for view in model.views.values():
        write(f"{view.id}.md", view_page(model, view, rules))
    write("decisions.md", _decisions_page(model))
    write("README.md", _index_page(model, rules))

    for stale in docs_dir.glob("*.md"):
        if stale not in written and stale.read_text(encoding="utf-8").startswith(MARKER):
            stale.unlink()
            result.removed.append(stale)
    return result


def view_page(model: Model, view: View, rules: Rules, back: str = "README.md", up: str = "../..") -> str:
    """Markdown page for one view. `up` is the path from the page back to the repo root."""
    members = view_members(at_state(model, view.state), view, rules)
    kind = "C4 " + view.kind.removeprefix("c4-") + " view" if view.is_c4 else "ArchiMate view" + (f" · {view.viewpoint} viewpoint" if view.viewpoint else "")
    state_note = {"baseline": " · current state", "target": " · target state"}.get(view.state, "")
    source = f" · source `{view.file}`" if view.file else ""
    out = [f"# {view.name}", "", f"*{kind}{state_note}*{source} · [index]({back})", ""]
    if view.documentation:
        out += [view.documentation.strip(), ""]
    out += ["```mermaid", render_view(model, view, rules).rstrip(), "```", ""]
    if view.state == "change" and view_has_changes(model, view, rules):
        out += [f"*{LEGEND}*", ""]
        for state, title in (("baseline", "Current state"), ("target", "Target state")):
            out += [f"<details><summary>{title}</summary>", "", "```mermaid", render_view(model, view, rules, state).rstrip(), "```", "", "</details>", ""]
    out += ["## Elements", "", "| Element | Type | Layer | C4 | State | Description |", "|---|---|---|---|---|---|"]
    for element_id in members:
        el = model.elements[element_id]
        doc = " ".join(el.documentation.split()).replace("|", "\\|")
        state = "" if el.state == "existing" else el.state
        out.append(f"| {el.name} (`{el.id}`) | {el.type} | {rules.layers[rules.layer_of(el.type)]['label']} | {el.c4 or ''} | {state} | {doc} |")
    related = adrs_affecting(model, set(members) | {view.id})
    if related:
        out += ["", "## Related decisions", ""]
        out += [f"- [{r.id}: {r.title}]({up}/{r.file}) — *{r.status}*" for r in related]
    return "\n".join(out) + "\n"


def _decisions_page(model: Model) -> str:
    out = [f"# Decisions — {model.name or model.sa}", "", "[index](README.md)", ""]
    if not model.adrs:
        return "\n".join(out + ["No decisions recorded yet. Create one with `python3 -m a4m new-adr <sa> \"Title\"`."]) + "\n"
    out += ["| ADR | Title | Status | Date | Affects |", "|---|---|---|---|---|"]
    for r in sorted(model.adrs, key=lambda r: r.id):
        affects = ", ".join(f"`{a}`" for a in r.affects)
        out.append(f"| [{r.id}](../../{r.file}) | {r.title} | {r.status} | {r.date} | {affects} |")
    return "\n".join(out) + "\n"


def _index_page(model: Model, rules: Rules) -> str:
    out = [f"# {model.name or model.sa}", ""]
    out += [f"*{model.kind}* · status **{model.status}**" + (f" · owner {model.owner}" if model.owner else "") + " · [all SAs](../README.md)", ""]
    if model.documentation:
        out += [model.documentation.strip(), ""]
    own = model.own_elements()
    counts: dict[str, int] = {}
    for el in own:
        counts[rules.layer_of(el.type)] = counts.get(rules.layer_of(el.type), 0) + 1
    out += [
        f"{len(own)} elements · {len(model.own_relationships())} relationships · {len(model.views)} views · {len(model.adrs)} decisions",
        "",
        "Open in Archi: *File → Import → Open Exchange XML Model* → "
        f"`build/{model.sa}.oef.xml` (run `python3 -m a4m build {model.sa}` first).",
        "",
        "## Views",
        "",
        "| View | Kind | Elements |",
        "|---|---|---|",
    ]
    for view in model.views.values():
        out.append(f"| [{view.name}]({view.id}.md) | {view.kind} | {len(view_members(model, view, rules))} |")
    out += ["", "## Elements per layer", "", "| Layer | Count |", "|---|---|"]
    out += [f"| {rules.layers[layer]['label']} | {counts[layer]} |" for layer in rules.layer_order() if layer in counts]
    out += _change_section(model)
    out += _cross_sa_section(model)
    out += ["", "## Decisions", "", "See [decisions.md](decisions.md)."]
    return "\n".join(out) + "\n"


def _change_section(model: Model) -> list[str]:
    changes = [c for c in [*model.own_elements(), *model.own_relationships()] if c.state != "existing"]
    if not changes:
        return []
    out = ["", "## Changes (current → target)", "", "| State | Kind | Item |", "|---|---|---|"]
    for c in sorted(changes, key=lambda c: (["new", "changed", "retiring"].index(c.state), c.id)):
        if hasattr(c, "source"):
            out.append(f"| {c.state} | {c.type} | `{c.source}` → `{c.target}`{' — ' + c.name if c.name else ''} |")
        else:
            out.append(f"| {c.state} | {c.type} | {c.name} (`{c.id}`) |")
    return out


def _cross_sa_section(model: Model) -> list[str]:
    uses = sorted({r.source.split("/")[0] for r in model.own_relationships() if "/" in r.source}
                  | {r.target.split("/")[0] for r in model.own_relationships() if "/" in r.target})
    used_by = sorted({r.sa for r in model.relationships.values() if r.foreign and r.sa != model.sa
                      and (r.source in model.elements and not model.elements[r.source].foreign
                           or r.target in model.elements and not model.elements[r.target].foreign)})
    exports = sorted(model.elements) if model.exports == "*" else model.exports
    out = []
    if uses or used_by or exports:
        out += ["", "## Other solution architectures", ""]
        if uses:
            out.append("- **Uses:** " + ", ".join(f"[{sa}](../{sa}/README.md)" for sa in uses))
        if used_by:
            out.append("- **Used by:** " + ", ".join(f"[{sa}](../{sa}/README.md)" for sa in used_by))
        if exports:
            shown = [e for e in exports if e in model.elements and not model.elements[e].foreign]
            out.append(f"- **Exports** (`{model.sa}/<id>`): " + ("all elements" if model.exports == "*" else ", ".join(f"`{e}`" for e in shown)))
    return out
